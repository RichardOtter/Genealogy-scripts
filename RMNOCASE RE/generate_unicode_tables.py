"""Generate the Unicode tables used by the standalone RMNOCASE extension."""

import unicodedata
from pathlib import Path

from insert_test_data import ROOTSMAGIC_CASEFOLD_IDENTITY


UNICODE_VERSION = "17.0.0"
OUTPUT = Path(__file__).with_name("rmnocase_unicode.h")


def main():
    if unicodedata.unidata_version != UNICODE_VERSION:
        raise RuntimeError(
            f"Unicode {UNICODE_VERSION} is required; "
            f"this Python uses {unicodedata.unidata_version}"
        )

    mappings = []
    values = []
    properties = []
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        char = chr(codepoint)
        folded = char if char in ROOTSMAGIC_CASEFOLD_IDENTITY else char.casefold()
        normalized = unicodedata.normalize("NFD", folded)
        if normalized != char:
            mappings.append((codepoint, len(values), len(normalized)))
            values.extend(map(ord, normalized))
        combining = unicodedata.combining(char)
        nonspacing = unicodedata.category(char) == "Mn"
        if combining or nonspacing:
            properties.append((codepoint, combining, int(nonspacing)))

    with OUTPUT.open("w", encoding="ascii", newline="\n") as out:
        out.write("/* Generated by generate_unicode_tables.py; do not edit. */\n")
        out.write(f'#define RMNOCASE_UNICODE_VERSION "{UNICODE_VERSION}"\n')
        out.write("static const uint32_t mapping_values[] = {\n")
        for i in range(0, len(values), 12):
            out.write("    " + ", ".join(f"0x{v:X}" for v in values[i:i + 12]) + ",\n")
        out.write("};\nstatic const Mapping mappings[] = {\n")
        for codepoint, offset, length in mappings:
            out.write(f"    {{0x{codepoint:X}, {offset}, {length}}},\n")
        out.write("};\nstatic const Property properties[] = {\n")
        for codepoint, combining, nonspacing in properties:
            out.write(f"    {{0x{codepoint:X}, {combining}, {nonspacing}}},\n")
        out.write("};\n")
    print(f"Generated {OUTPUT.name} using Unicode {UNICODE_VERSION}.")


if __name__ == "__main__":
    main()
